function toDhikr(type: AzkarType, items: Entry[]): Dhikr[] {
  return items.map((item, index) => ({
    id: `${type}-${item.id}`,
    type,
    order: index + 1,
    text: item.text,
    repetitions: item.repetitions,
    source: `${item.source} — ${item.reference}`,
  }));
}

